// Reads docs/animationFrames/p0..pN.svg (artwork overlays, same 1280x720 artboard as the circle frames)
// and writes app/utils/artworkGeometry.ts. Run with: npm run build:artwork
//
// Conventions in the SVGs:
//   - first child <g id="pN"> is the frame; its <rect> (background) is ignored
//   - every other child is a top-level ITEM: a <path> or a <g> of paths, matched across frames by id
//   - an item missing from a frame is hidden in that frame
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIR = join(ROOT, 'docs/animationFrames')
const OUT = join(ROOT, 'app/utils/artworkGeometry.ts')

// Minimal XML tree parser, enough for Figma-style exports (no CDATA, no entities in attributes)
function parse(xml) {
  const root = { tag: '#root', attrs: {}, children: [] }
  const stack = [root]
  for (const m of xml.matchAll(/<(\/?)([a-zA-Z][\w:-]*)([^>]*?)(\/?)>/g)) {
    const [, close, tag, attrStr, selfClose] = m
    if (close) {
      stack.pop()
      continue
    }
    const attrs = {}
    for (const a of attrStr.matchAll(/([\w:-]+)="([^"]*)"/g)) attrs[a[1]] = a[2]
    const node = { tag, attrs, children: [] }
    stack.at(-1).children.push(node)
    if (!selfClose) stack.push(node)
  }
  return root
}

function leavesOf(node, inheritedFill, out = []) {
  const fill = node.attrs.fill ?? inheritedFill
  if (node.tag === 'path') {
    const leaf = { id: node.attrs.id, d: node.attrs.d }
    if (fill && fill !== 'none') leaf.fill = fill
    if (node.attrs['fill-rule']) leaf.fillRule = node.attrs['fill-rule']
    out.push(leaf)
  }
  else if (node.tag === 'g') {
    node.children.forEach(c => leavesOf(c, fill, out))
  }
  else if (node.tag !== 'rect') {
    console.warn(`  ! unsupported <${node.tag}> ignored`)
  }
  return out
}

function itemOf(node) {
  const leaves = leavesOf(node)
  const item = { id: node.attrs.id, group: node.tag === 'g', leaves }
  // Group whose paths all share one fill: keep the fill on the group (one tween recolours everything)
  if (item.group) {
    const fills = new Set(leaves.map(l => l.fill))
    if (fills.size === 1 && leaves[0].fill) {
      item.fill = leaves[0].fill
      leaves.forEach(l => delete l.fill)
    }
  }
  return item
}

const files = readdirSync(DIR)
  .filter(f => /^p\d+\.svg$/.test(f))
  .sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)))

const frames = files.map((f) => {
  const svg = parse(readFileSync(join(DIR, f), 'utf8')).children.find(n => n.tag === 'svg')
  const frame = svg.children.find(n => n.tag === 'g')
  const items = {}
  const order = []
  for (const child of frame.children) {
    if (child.tag === 'rect') continue
    const item = itemOf(child)
    if (!item.id) {
      console.warn(`  ! ${f}: top-level <${child.tag}> without id ignored`)
      continue
    }
    items[item.id] = item
    order.push(item.id)
  }
  console.log(`${f}: ${order.map(id => `${id}(${items[id].leaves.length})`).join(', ')}`)
  return { items, order }
})

// Global draw order: topological merge of every frame's order (first appearance breaks ties)
const first = []
const before = new Map() // id -> Set of ids that must be drawn after it
for (const { order } of frames) {
  order.forEach((id, i) => {
    if (!first.includes(id)) first.push(id)
    if (i > 0) {
      if (!before.has(order[i - 1])) before.set(order[i - 1], new Set())
      before.get(order[i - 1]).add(id)
    }
  })
}
const indeg = Object.fromEntries(first.map(id => [id, 0]))
before.forEach(set => set.forEach((id) => { indeg[id]++ }))
const merged = []
const left = [...first]
while (left.length) {
  const next = left.find(id => indeg[id] === 0)
  if (!next) throw new Error(`Conflicting draw order between frames near: ${left.join(', ')}`)
  merged.push(next)
  left.splice(left.indexOf(next), 1)
  before.get(next)?.forEach((id) => { indeg[id]-- })
}

const ts = `// GENERATED by scripts/build-artwork.mjs from docs/animationFrames/p*.svg. Do not edit by hand (npm run build:artwork).

export interface ArtLeaf {
  id: string
  d: string
  fill?: string
  fillRule?: string
}

export interface ArtNode {
  id: string
  group: boolean
  fill?: string // group-level fill, when every path of the group shares it
  leaves: ArtLeaf[]
}

// Per frame: top-level item id -> geometry (an item missing from a frame is hidden in it)
export const ARTWORK_FRAMES: Record<string, ArtNode>[] = ${JSON.stringify(frames.map(f => f.items), null, 2)}

// Draw order, back to front, merged across all frames
export const ARTWORK_ORDER: string[] = ${JSON.stringify(merged)}
`
writeFileSync(OUT, ts)
console.log(`\nwrote ${OUT.replace(ROOT + '/', '')} (${frames.length} frames, order: ${merged.join(' > ')})`)
